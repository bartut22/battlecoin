import { chromium, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
const browser=await chromium.launch({channel:'msedge',headless:true})
try {
const page=await browser.newPage({viewport:{width:1440,height:960}})
page.setDefaultTimeout(15000)
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
await page.addInitScript(()=>localStorage.setItem('battlecoin_session',JSON.stringify({username:'Tutorial tester'})))
await page.goto('http://127.0.0.1:5178')
await expect(page.locator('.canvas-host canvas')).toBeVisible()
await page.locator('.canvas-host canvas').evaluate(canvas=>canvas.dataset.identity='original')
await expect(page.locator('.workspace')).toBeVisible()
await expect(page.getByRole('complementary',{name:'Chip dialogue'})).toBeVisible()
await expect(page.locator('.rail-tabs')).toHaveCount(0)
await expect(page.locator('.deck-card')).toHaveCount(0)
await expect(page.locator('.market-strip')).toContainText('18.5c')
await expect(page.locator('.market-strip')).toContainText('81.5c')
await mkdir('artifacts',{recursive:true})
await page.screenshot({path:'artifacts/tutorial-integrated.png',fullPage:true})
const next=()=>page.getByRole('button',{name:'Tap to continue',exact:true}).click()
await next();await next();await next()
const card=await page.getByRole('button',{name:'Buy 10 UP card'}).boundingBox()
const lane=await page.getByRole('button',{name:/BUY LANE/}).boundingBox()
await page.mouse.move(card.x+card.width/2,card.y+card.height/2)
await page.mouse.down()
await page.mouse.move(lane.x+lane.width/2,lane.y+lane.height/2,{steps:12})
await expect(page.locator('.tutorial-drag')).toContainText('$1.90')
await page.mouse.up()
await expect(page.locator('.tutorial-dialogue-body')).toContainText('Nice!')
await expect(page.locator('.capital')).toContainText('$98.10')
await next();await next();await next();await next();await next();await next();await next()
await page.getByRole('button',{name:'Bid 81c',exact:true}).click()
await next();await next()
await page.getByRole('button',{name:'Sell Lane · 18¢ Bid',exact:true}).click()
await expect(page.locator('.tutorial-dialogue-body')).toContainText("Can't sell")
await next();await next()
await page.getByRole('button',{name:'Start Match',exact:true}).click()
await expect(page.locator('.rail-tabs')).toBeVisible()
await expect(page.locator('.capital-title')).toContainText('$100.00')
await expect(page.locator('.canvas-host canvas')).toHaveAttribute('data-identity','original')
await page.getByRole('button',{name:'Tutorial',exact:true}).click()
await expect(page.locator('.capital-title')).toContainText('$100.00')
await expect(page.locator('.canvas-host canvas')).toHaveAttribute('data-identity','original')
await page.setViewportSize({width:390,height:844})
await page.screenshot({path:'artifacts/tutorial-integrated-mobile.png',fullPage:true})
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow')
await next();await next();await next()
await page.getByRole('button',{name:'Buy 10 UP card'}).press('Enter')
await page.getByRole('button',{name:/BUY LANE/}).click()
await expect(page.locator('.capital')).toContainText('$98.10')
await next();await next();await next();await next();await next();await next();await next()
await page.getByRole('button',{name:'Ask 82c',exact:true}).click()
await next();await next()
await page.getByRole('button',{name:'Buy Lane · 19¢ Ask',exact:true}).click()
await expect(page.locator('.tutorial-dialogue-body')).toContainText('Exactly!')
if(errors.length)throw Error(errors.join('\n'))
console.log('Passed: same canvas across mode switches, fixed quotes, container swaps, actual practice ledger purchase, isolated live capital, drag/keyboard purchase, quiz branches, mobile layout.')
} finally { await browser.close() }
